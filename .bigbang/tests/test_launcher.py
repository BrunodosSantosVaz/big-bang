"""Launcher safety net (epic #222): a system is born by copying this repository (GitHub template), then the Foundation
runs `bb init` (F0) and `bb gerar --esteira` (F5). Nothing the framework keeps for itself may leak into the system.

The template is rebuilt from the files Git tracks (the working-tree content of each), exactly what "Use this
template" copies; untracked local files never count."""
import contextlib
import io
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
import unittest
from unittest.mock import patch

from _raiz import RAIZ, importar_bb

importar_bb()
from bb import cli, generator, init, verify  # noqa: E402
from bb.errors import EXIT_OK  # noqa: E402

FRAMEWORK_REPOSITORY = "BrunodosSantosVaz/big-bang"
# The guard must be the job's own `if:` (four spaces in), never a comment or an env value; it may only be narrowed
# further with `&& (...)`: exactly one balanced parenthesized group, so no top-level `||` can widen it.
GUARD_PREFIX = re.compile(rf"^    if: github\.repository == '{re.escape(FRAMEWORK_REPOSITORY)}'(.*)$", re.M)


def narrowing_only(rest):
    """True when `rest` is empty or ` && (<one balanced group>)`, nothing after it.

    Limit: parentheses inside quoted strings are counted too, so a crafted `&& (a == '(') || (b)` would pass. The
    framework's own workflows never quote parentheses in a guard; the review covers that residual case."""
    rest = rest.rstrip()
    if not rest:
        return True
    if not rest.startswith(" && ("):
        return False
    depth = 0
    for index, char in enumerate(rest[4:], start=4):
        depth += {"(": 1, ")": -1}.get(char, 0)
        if depth == 0:
            return index == len(rest) - 1
    return False


def guarded(body):
    match = GUARD_PREFIX.search(body)
    return bool(match) and narrowing_only(match.group(1))
# A job header: two spaces, the id, a colon, then nothing but an optional comment.
JOB_HEADER = re.compile(r"^  ([\w-]+):[ \t]*(?:#.*)?$", re.M)
# Every top-level entry the template ships, and what the Foundation does with it. A new entry needs a deliberate
# decision here, so nothing of the framework leaks into a new system unnoticed.
ROOT_ENTRIES = {
    ".agents": "kept: generated skills, regenerated by bb gerar",
    ".bigbang": "kept: the framework layer",
    ".bigbang-docs.json": "framework only: removed (private) or replaced by the system's manifest (public)",
    ".claude": "kept: generated settings and agents",
    ".github": "kept: bb-framework-* removed by F5",
    ".gitignore": "kept",
    ".gitleaksignore": "kept: fingerprints of framework commits, which a template-born history never contains",
    "AGENTS.md": "kept: generated block refreshed; the marked bigbang:framework segment removed by bb init",
    "CLAUDE.md": "kept",
    "CODE_OF_CONDUCT.md": "replaced by the system's (DOC-16)",
    "CONTRIBUTING.md": "replaced by the system's (DOC-16)",
    "LICENSE": "moved to .bigbang/ (the system gets its own when public)",
    "README.md": "moved to .bigbang/ and replaced by the system's",
    "SECURITY.md": "replaced by the system's (DOC-16)",
}
FAKE_GH = r'''
import json, os, sys
args = sys.argv[1:]
with open(os.environ["GH_LOG"], "a", encoding="utf-8") as log:
    log.write(json.dumps(args) + "\n")
if args[:1] == ["api"] and args[1].startswith("licenses/"):
    print("MIT License\n\nCopyright (c) [year] [fullname]\n")
elif args[:1] == ["api"] and args[1].startswith("users/"):
    print("Pessoa Fictícia")
else:
    sys.stderr.write("unexpected gh call: " + " ".join(args) + "\n"); sys.exit(1)
'''


def tracked_files():
    try:
        result = subprocess.run(["git", "-C", RAIZ, "ls-files", "-z"], capture_output=True, check=False)
    except FileNotFoundError:
        return None
    if result.returncode:
        return None
    return [name for name in result.stdout.decode("utf-8").split("\0") if name]


def build_template(destination):
    """Copy every tracked file (working-tree content) into destination; deleted-but-tracked files are skipped."""
    for relative in tracked_files():
        source = os.path.join(RAIZ, *relative.split("/"))
        if not os.path.isfile(source):
            continue
        target = os.path.join(destination, *relative.split("/"))
        os.makedirs(os.path.dirname(target), exist_ok=True)
        shutil.copy2(source, target)


class Launcher(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if tracked_files() is None:
            raise unittest.SkipTest("sem repositório Git: o template é definido pelos arquivos versionados")

    def setUp(self):
        self.folder = tempfile.TemporaryDirectory()
        self.root = os.path.join(self.folder.name, "novo-sistema")
        build_template(self.root)
        log = os.path.join(self.folder.name, "gh.log")
        fake = os.path.join(self.folder.name, "gh_falso.py")
        with open(fake, "w", encoding="utf-8") as handle:
            handle.write(FAKE_GH)
        environment = {"BB_GH": f'"{sys.executable}" "{fake}"', "GH_LOG": log}
        self.previous = {key: os.environ.get(key) for key in environment}
        os.environ.update(environment)

    def tearDown(self):
        for key, value in self.previous.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value
        self.folder.cleanup()

    def path(self, relative):
        return os.path.join(self.root, *relative.split("/"))

    def read(self, relative):
        with open(self.path(relative), encoding="utf-8") as handle:
            return handle.read()

    def bb(self, *argv):
        output = io.StringIO()
        with contextlib.redirect_stdout(output), contextlib.redirect_stderr(output):
            code = cli.main(["--raiz", self.root, *argv])
        return code, output.getvalue()

    def found(self, *options, visibility="privado"):
        args = ["init", "--nome", "Sistema Novo", "--dono", "dona-teste", "--repositorio", "dona-teste/sistema-novo",
                "--sem-github", *options]
        if visibility == "publico":
            args += ["--visibilidade", "publico", "--licenca", "MIT"]
        wiki = {"commit": "a" * 40, "branch": "master"}
        with patch.object(init.documentation, "preflight", return_value=wiki):
            code, output = self.bb(*args)
        self.assertEqual(code, EXIT_OK, output)
        code, output = self.bb("gerar", "--esteira")
        self.assertEqual(code, EXIT_OK, output)

    def framework_workflows(self):
        folder = self.path(".github/workflows")
        names = sorted(os.listdir(folder)) if os.path.isdir(folder) else []
        return [name for name in names if name.startswith(generator.FRAMEWORK_WORKFLOW_PREFIX)]

    # --- the template, before any Foundation step ----------------------------------------------------------------

    def test_template_is_not_founded(self):
        self.assertFalse(os.path.exists(self.path("bigbang.toml")))
        self.assertIn("ainda não foi fundado", self.read("AGENTS.md"))
        self.assertFalse(generator.pipeline_installed(self.root))
        self.assertEqual(verify.run(self.root), [])
        self.assertEqual(generator.changes(generator.build_plan(self.root), self.root), [])

    def test_template_ships_only_guarded_framework_workflows(self):
        folder = self.path(".github/workflows")
        for name in sorted(os.listdir(folder)):
            self.assertTrue(name.startswith(generator.FRAMEWORK_WORKFLOW_PREFIX),
                            f"{name}: workflow sem o prefixo bb-framework- instalaria a esteira antes da F5")
            section = self.read(f".github/workflows/{name}").split("\njobs:\n", 1)[1]
            marks = list(JOB_HEADER.finditer(section))
            self.assertTrue(marks, name)
            for mark, following in zip(marks, marks[1:] + [None]):
                body = section[mark.end():following.start() if following else len(section)]
                self.assertTrue(guarded(body), f"{name}: job {mark.group(1)} roda fora do repositório do framework")

    def test_guard_check_rejects_unguarded_jobs(self):
        section = ("  a:\n    if: github.repository == 'BrunodosSantosVaz/big-bang'\n    runs-on: x\n"
                   "  b:   \n    runs-on: x\n  c:  # comment\n    runs-on: x\n"
                   "  d:\n    steps:\n      # if: github.repository == 'BrunodosSantosVaz/big-bang'\n"
                   "  e:\n    if: github.repository == 'BrunodosSantosVaz/big-bang' && (github.event_name != 'x')\n"
                   "  f:\n    if: github.repository == 'BrunodosSantosVaz/big-bang' && true || true\n"
                   "  g:\n    if: github.repository == 'BrunodosSantosVaz/big-bang' && (a) || (true)\n"
                   "  h:\n    if: github.repository == 'BrunodosSantosVaz/big-bang' && (a || (b && c))\n")
        marks = list(JOB_HEADER.finditer(section))
        self.assertEqual([m.group(1) for m in marks], ["a", "b", "c", "d", "e", "f", "g", "h"])
        result = [guarded(section[m.end():n.start() if n else len(section)]) for m, n in zip(marks, marks[1:] + [None])]
        self.assertEqual(result, [True, False, False, False, True, False, False, True])

    def test_every_root_entry_has_a_foundation_decision(self):
        manifest = self.path(".bigbang-docs.json")
        if os.path.exists(manifest):
            with open(manifest, encoding="utf-8") as handle:
                self.assertEqual(json.load(handle)["repositorio"], FRAMEWORK_REPOSITORY)
        for name in sorted(os.listdir(self.root)):
            self.assertIn(name, ROOT_ENTRIES, f"{name}: entrada do template sem decisão para a Fundação")

    # --- after the Foundation ----------------------------------------------------------------------------------

    def assert_founded_cleanly(self, mode, workflow="grouping"):
        from bb import config as config_module
        config = config_module.load(self.root)
        self.assertEqual(config_module.get(config, "project.repository"), "dona-teste/sistema-novo")
        self.assertEqual(config_module.get(config, "project.mode"), mode)
        self.assertEqual(config_module.get(config, "workflow.model"), workflow)
        agents = self.read("AGENTS.md")
        self.assertNotIn("ainda não foi fundado", agents)
        base = ".bigbang/pipeline/AGENTS.base.md" if workflow == "grouping" else ".bigbang/AGENTS.base.md"
        self.assertIn(f"a partir de {base}", agents)
        project_part = agents.split("<!-- bigbang:fim -->", 1)[1]
        self.assertNotIn(FRAMEWORK_REPOSITORY, project_part, "instruções do próprio framework herdadas pelo sistema")
        self.assertNotIn("Modo do próprio framework", project_part)
        self.assertIn("Esta seção pertence ao projeto", project_part)
        self.assertNotIn("bigbang:framework", project_part)
        self.assertTrue(generator.pipeline_installed(self.root))
        self.assertEqual(self.framework_workflows(), [], "a F5 precisa remover a CI do framework")
        self.assertRegex(self.read("README.md"), r"(?m)^# Sistema Novo$")
        for name in ("CODE_OF_CONDUCT.md", "CONTRIBUTING.md", "SECURITY.md"):
            self.assertIn("dona-teste/sistema-novo", self.read(name))
        workflows = sorted(os.listdir(self.path(".github/workflows")))
        if workflow == "grouping":
            self.assertIn("bb-ci.yml", workflows)
            self.assertIn("bb-controller.yml", workflows)
            self.assertNotIn("bb-kanban.yml", workflows)
            with open(self.path("bigbang.toml"), "rb") as handle:
                raw = tomllib.load(handle)
            self.assertIn("project", raw, "um sistema v3 nasce com o bigbang.toml em inglês")
            self.assertEqual(raw["board"], {"model": "single", "number": 0, "labels": "v3", "owner": "dona-teste"})
            self.assertTrue(os.path.exists(self.path(".claude/skills/bb-reject/SKILL.md")))
        else:
            self.assertIn("bb-kanban.yml", workflows)
            self.assertNotIn("bb-controller.yml", workflows)
        self.assertEqual(verify.run(self.root), [])
        self.assertEqual(generator.changes(generator.build_plan(self.root), self.root), [],
                         "a segunda geração precisa ser idempotente")

    def test_private_default_mode(self):
        self.found()
        self.assert_founded_cleanly("normal")
        self.assertFalse(os.path.exists(self.path(".bigbang-docs.json")),
                         "manifesto da Wiki do framework herdado por um sistema privado")

    def test_private_flash_mode(self):
        self.found("--modo", "flash")
        self.assert_founded_cleanly("flash")
        self.assertIn("Modo Flash", self.read("AGENTS.md"))

    def test_autonomous_mode_needs_the_v3_workflow(self):
        self.found("--mode", "autonomous")
        self.assert_founded_cleanly("autonomous")
        self.assertIn("Modo autônomo", self.read("AGENTS.md"))
        code, output = self.bb("init", "--nome", "Outro", "--dono", "d", "--repositorio", "d/o", "--sem-github",
                               "--modo", "autonomous", "--fluxo", "epic-branch", "--simular")
        self.assertNotEqual(code, EXIT_OK)
        self.assertIn("autonomous", output)

    def test_previous_workflow_stays_available(self):
        self.found("--workflow", "epic-branch")
        self.assert_founded_cleanly("normal", workflow="epic-branch")
        with open(self.path("bigbang.toml"), "rb") as handle:
            self.assertIn("projeto", tomllib.load(handle), "o fluxo anterior mantém o bigbang.toml em português")

    def test_public_gets_its_own_manifest(self):
        environment = dict(os.environ, GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@t", GIT_COMMITTER_NAME="t",
                           GIT_COMMITTER_EMAIL="t@t")
        for command in (["init", "-q"], ["add", "-A"], ["commit", "-q", "-m", "template"]):
            subprocess.run(["git", "-C", self.root, *command], check=True, env=environment, capture_output=True)
        head = subprocess.run(["git", "-C", self.root, "rev-parse", "HEAD"], check=True, capture_output=True,
                              text=True).stdout.strip()
        self.found(visibility="publico")
        self.assert_founded_cleanly("normal")
        with open(self.path(".bigbang-docs.json"), encoding="utf-8") as handle:
            manifest = json.load(handle)
        self.assertEqual(manifest["repositorio"], "dona-teste/sistema-novo")
        self.assertEqual(manifest["paginas"], {})
        self.assertEqual(manifest["codigo"]["commit"], head)
        self.assertTrue(self.read("LICENSE").startswith("MIT License"))

    def test_compiled_profile_after_f2(self):
        self.found()
        text = self.read("bigbang.toml")
        text = init.set_value(text, "delivery", "profile", "compiled")
        text = init.set_value(text, "delivery", "target", "")
        with open(self.path("bigbang.toml"), "w", encoding="utf-8") as handle:
            handle.write(text)
        code, output = self.bb("generate")
        self.assertEqual(code, EXIT_OK, output)
        self.assertTrue(os.path.exists(self.path(".github/workflows/bb-candidate.yml")))
        self.assertFalse(os.path.exists(self.path(".github/workflows/bb-rollback.yml")))
        self.assertEqual(verify.run(self.root), [])


if __name__ == "__main__":
    unittest.main()
